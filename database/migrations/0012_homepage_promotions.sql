CREATE TABLE IF NOT EXISTS app.homepage_promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 2 AND 100),
    subtitle TEXT NOT NULL DEFAULT '' CHECK (char_length(subtitle) <= 220),
    badge TEXT NOT NULL DEFAULT 'ویژه' CHECK (char_length(badge) <= 40),
    image_url TEXT NOT NULL,
    cta_text TEXT NOT NULL DEFAULT 'مشاهده آگهی‌ها' CHECK (char_length(cta_text) <= 40),
    target_page TEXT NOT NULL DEFAULT 'listings' CHECK (target_page IN ('listings','map','index','areas','register','home')),
    sort_order INTEGER NOT NULL DEFAULT 1 CHECK (sort_order BETWEEN 1 AND 20),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

